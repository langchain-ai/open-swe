/*
 * Sidebar, retokenized onto CORE 14.
 *
 * The shadcn `sidebar-*` colour family collapses into the CORE 14 surfaces: the
 * shell is `sidebar`, hover is `hover`, the current item is `selected` (the
 * vendored file painted hover and active identically, so an active row was
 * invisible once the pointer left it), rules are `line`, focus is `primary`.
 *
 * Two structural fixes came with the port. The `outline` menu-button variant
 * drew its edge with an arbitrary box-shadow wrapping the sidebar border token
 * in `hsl()`, the shadcn-v3 bare-triplet convention, which cannot resolve
 * against a hex token and so rendered nothing; it is a real `border` now. And
 * the two collapsed-width calculations moved out of arbitrary values into
 * component-scoped custom properties declared next to the widths they derive
 * from.
 *
 * The width/left/right transitions stay: a sidebar that collapses is animating
 * its own geometry, which is the one thing "motion is transform and opacity"
 * cannot express. Everything else animates colour only.
 */

