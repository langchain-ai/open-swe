/*
 * THE SCROLLBAR LAW REACHES THE SIDEBAR (wiki 02).
 *
 * This region used to delete its scrollbar outright -- `[scrollbar-width:none]`
 * plus `[&::-webkit-scrollbar]:hidden` on a raw `overflow-auto` box -- which is
 * the opposite failure to the one the law is usually fixing. A nav taller than
 * the viewport scrolled with no indication that it could, so the rows below the
 * fold simply did not exist for anyone who did not try. Hiding the bar is not
 * compliance with "the track is invisible"; it is the other way to be wrong.
 *
 * It is a real ScrollArea now, on the same overlay thumb as every other scroll
 * surface. `min-h-0 flex-1` keeps it the growing child of the sidebar's column,
 * so the root resolves to a definite height and the viewport's `size-full` has
 * something to be a fraction of. The column layout the rows sit in moved to the
 * viewport, because the viewport is the box that now scrolls.
 */
function SidebarContent({
  className,
  viewportClassName,
  ...props
}: React.ComponentProps<typeof ScrollArea>) {
  return (
    <ScrollArea
      data-slot="sidebar-content"
      data-sidebar="content"
      className={cn("min-h-0 flex-1", className)}
      viewportClassName={cn(
        "flex flex-col gap-0 group-data-[collapsible=icon]:overflow-hidden",
        viewportClassName
      )}
      {...props}
    />
  );
}

